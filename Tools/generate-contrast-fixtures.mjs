#!/usr/bin/env node
// Emits the contrast fixture that ColorCore/Analysis is cross-checked against.
//
// Read the tolerances below before trusting this file, because the two algorithms it
// covers are validated to very different standards:
//
//   APCA  — colorjs.io is a genuine oracle. The Swift implementation is transcribed
//           from that package's source, so agreement should be near float-exact, and
//           any drift is a real transcription bug.
//
//   WCAG  — colorjs.io is NOT ground truth, for two independent reasons. It computes
//           luminance as XYZ-D65 Y, which uses the full-precision matrix row
//           (0.2126729/0.7151522/0.072175) where WCAG's text specifies the rounded
//           0.2126/0.7152/0.0722; and it linearizes at sRGB's 0.04045 where WCAG
//           specifies 0.03928. Measured divergence over 20,000 random 8-bit pairs is
//           up to 1.97e-4 relative. Correctness for WCAG therefore rests on the
//           published anchors asserted in Swift (black on white is exactly 21:1, a
//           colour against itself is exactly 1:1); this fixture only catches gross
//           error across a wide sample.
//
// Colours are deliberately kept inside the sRGB gamut. APCA is defined on sRGB, and
// colorjs.io's implementation explicitly leaves out-of-gamut input unspecified — it
// raises a negative value to a fractional power and yields NaN. ColorCore gamut-maps
// instead, so out-of-gamut pairs would compare a defined answer against an undefined
// one and prove nothing.

import { writeFileSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import Color from "colorjs.io";

const here = dirname(fileURLToPath(import.meta.url));
const version = JSON.parse(
	readFileSync(join(here, "node_modules", "colorjs.io", "package.json"), "utf8"),
).version;

// A deterministic spread rather than random sampling, so regenerating the fixture on
// another machine produces the same file and a diff means something changed.
const CHANNELS = [0, 17, 68, 128, 187, 238, 255];
const swatches = [];
for (const r of CHANNELS) {
	for (const g of CHANNELS) {
		for (const b of CHANNELS) {
			// Every 11th, to keep the fixture in the low hundreds rather than 343².
			if ((r + g * 7 + b * 13) % 11 === 0) {
				swatches.push([r, g, b]);
			}
		}
	}
}

const hex = ([r, g, b]) =>
	"#" + [r, g, b].map((v) => v.toString(16).padStart(2, "0")).join("");

const pairs = [];
for (let i = 0; i < swatches.length; i++) {
	// Pair each swatch with the one a third of the way along, plus black and white —
	// the extremes are where the flare clamp and the low-clip actually engage.
	const partners = [
		swatches[(i + Math.floor(swatches.length / 3)) % swatches.length],
		[0, 0, 0],
		[255, 255, 255],
	];
	for (const partner of partners) {
		const text = new Color("srgb", swatches[i].map((v) => v / 255));
		const background = new Color("srgb", partner.map((v) => v / 255));
		pairs.push({
			text: hex(swatches[i]),
			background: hex(partner),
			wcag: Color.contrast(text, background, "WCAG21"),
			// Argument order is (background, foreground). Recording both polarities so
			// a swapped argument in Swift cannot pass by symmetry.
			apca: Color.contrast(background, text, "APCA"),
			apcaReversed: Color.contrast(text, background, "APCA"),
		});
	}
}

const fixture = {
	generator: {
		library: "colorjs.io",
		version,
		apcaVersion: "0.0.98G",
		note: "Generated by Tools/generate-contrast-fixtures.mjs — do not edit by hand.",
		wcagIsApproximate: true,
		wcagMaxRelativeDivergence: 1.97e-4,
	},
	pairs,
};

const out = join(here, "..", "ColorKitTests", "Fixtures", "contrast-vectors.json");
writeFileSync(out, JSON.stringify(fixture));
console.log(`pairs       ${pairs.length}`);
console.log(`written to  ${out}`);
